// Horizontal cinema reel (4 across)
function renderCinema({ canvas, images, frame, note }: RenderArgs) {
  const F = fontFamilies();
  const m = measureCtx();

  const pw = 560;
  const ph = 420;
  const gap = 24;
  const padX = 60;
  const W = padX * 2 + 4 * pw + 3 * gap;
  const holeTop = 50;
  const photoY = holeTop + 34 + 26;
  const holeBottom = photoY + ph + 26;
  const footBase = holeBottom + 34 + 76;
  const H = footBase + 56;

  const ctx = prepareCanvas(canvas, W, H);

  ctx.fillStyle = frame.paper;
  ctx.fillRect(0, 0, W, H);

  ctx.fillStyle = "rgba(217,199,160,0.88)";
  for (let x = padX; x < W - padX - 20; x += 44) {
    roundRect(ctx, x, holeTop, 22, 34, 5);
    ctx.fill();
    roundRect(ctx, x, holeBottom, 22, 34, 5);
    ctx.fill();
  }

  images.forEach((image, i) => {
    const x = padX + i * (pw + gap);
    drawCover(ctx, image, x, photoY, pw, ph);
    ctx.strokeStyle = "rgba(217,199,160,0.35)";
    ctx.lineWidth = 3;
    ctx.strokeRect(x, photoY, pw, ph);
  });

  drawText(ctx, "SHUTTER CINEMA · 35MM", padX, footBase, {
    font: `20px ${F.mono}`,
    color: frame.textColor,
    align: "left",
    alpha: 0.6,
    spacing: 5,
  });
  drawText(ctx, "ISO 400 · 4 FRAMES", W - padX, footBase, {
    font: `20px ${F.mono}`,
    color: frame.textColor,
    align: "right",
    alpha: 0.6,
    spacing: 5,
  });

  // note (single line, shrinks to fit)
  const caption = note.trim() || "little memories";
  let size = 76;
  while (size > 36) {
    m.font = `700 ${size}px ${F.hand}`;
    if (m.measureText(caption).width <= 1300) break;
    size -= 4;
  }
  drawText(ctx, caption, W / 2, footBase + 6, {
    font: `700 ${size}px ${F.hand}`,
    color: frame.accent,
  });
}

// 2×2 polaroid prints on kraft paper
function renderPolaroid({ canvas, images, frame, note }: RenderArgs) {
  const F = fontFamilies();
  const m = measureCtx();

  const W = 1200;
  const pad = 90;
  const colGap = 70;
  const rowGap = 64;
  const cardW = (W - pad * 2 - colGap) / 2;
  const photo = cardW - 56;
  const cardH = 28 + photo + 110;
  const cardsTop = 150;

  const noteFont = `700 80px ${F.hand}`;
  const lines = wrapText(m, note.trim() || "little memories", noteFont, 1000).slice(0, 2);

  const gridEnd = cardsTop + 2 * cardH + rowGap;
  const firstBase = gridEnd + 110;
  const lastBase = firstBase + (lines.length - 1) * 82;
  const H = lastBase + 110;

  const ctx = prepareCanvas(canvas, W, H);

  ctx.fillStyle = frame.paper;
  ctx.fillRect(0, 0, W, H);
  paperTexture(ctx, 0, 0, W, H);

  drawText(ctx, "SHUTTER INSTANT · 600", W / 2, 80, {
    font: `20px ${F.mono}`,
    color: frame.ink,
    alpha: 0.65,
    spacing: 7,
  });

  const tilt = [-2, 1.6, 1.2, -1.8];

  images.forEach((image, i) => {
    const col = i % 2;
    const row = Math.floor(i / 2);
    const cx = pad + col * (cardW + colGap) + cardW / 2;
    const cy = cardsTop + row * (cardH + rowGap) + cardH / 2;

    ctx.save();
    ctx.translate(cx, cy);
    ctx.rotate((tilt[i] * Math.PI) / 180);

    ctx.shadowColor = "rgba(40,25,10,0.38)";
    ctx.shadowBlur = 24;
    ctx.shadowOffsetX = 5;
    ctx.shadowOffsetY = 10;
    ctx.fillStyle = "#f6efe0";
    ctx.fillRect(-cardW / 2, -cardH / 2, cardW, cardH);
    ctx.shadowColor = "transparent";

    drawCover(ctx, image, -cardW / 2 + 28, -cardH / 2 + 28, photo, photo);

    drawText(ctx, `frame ${i + 1}`, 0, cardH / 2 - 36, {
      font: `700 44px ${F.hand}`,
      color: frame.ink,
      alpha: 0.8,
    });

    // tape
    ctx.save();
    ctx.translate(0, -cardH / 2);
    ctx.rotate((-4 * Math.PI) / 180);
    ctx.fillStyle = "rgba(230,211,154,0.78)";
    ctx.fillRect(-56, -22, 112, 44);
    ctx.restore();

    ctx.restore();
  });

  lines.forEach((line, i) => {
    drawText(ctx, line, W / 2, firstBase + i * 82, {
      font: noteFont,
      color: frame.accent,
    });
  });
}

// 2×2 airmail postcard
function renderPostcard({ canvas, images, frame, note }: RenderArgs) {
  const F = fontFamilies();
  const m = measureCtx();

  const W = 1200;
  const border = 36;
  const padIn = 50;
  const innerX = border + padIn;
  const innerW = W - innerX * 2;
  const gap = 24;
  const cellW = (innerW - gap) / 2;
  const cellH = Math.round((cellW * 3) / 4);
  const gridTop = border + padIn + 190;
  const gridEnd = gridTop + 2 * cellH + gap;

  const noteFont = `700 64px ${F.hand}`;
  const lines = wrapText(m, note.trim() || "wish you were here ♡", noteFont, innerW).slice(0, 2);

  const ruleY = gridEnd + 50;
  const firstBase = ruleY + 70;
  const lastBase = firstBase + (lines.length - 1) * 66;
  const innerBottom = lastBase + 60;
  const H = innerBottom + border;

  const ctx = prepareCanvas(canvas, W, H);

  // airmail stripes
  ctx.fillStyle = "#f6efe0";
  ctx.fillRect(0, 0, W, H);
  const colors = ["#b3342a", "#f6efe0", "#2a3f6a", "#f6efe0"];
  const s = 36;
  for (let k = -Math.ceil(H / s) - 2; k < Math.ceil(W / s) + 2; k++) {
    ctx.fillStyle = colors[((k % 4) + 4) % 4];
    ctx.beginPath();
    ctx.moveTo(k * s, 0);
    ctx.lineTo(k * s + s, 0);
    ctx.lineTo(k * s + s - H, H);
    ctx.lineTo(k * s - H, H);
    ctx.closePath();
    ctx.fill();
  }

  // card paper
  ctx.fillStyle = frame.paper;
  ctx.fillRect(border, border, W - border * 2, H - border * 2);
  paperTexture(ctx, border, border, W - border * 2, H - border * 2);

  // header
  drawText(ctx, "Greetings from", innerX, border + padIn + 52, {
    font: `italic 58px ${F.serif}`,
    color: frame.accent,
    align: "left",
  });
  drawText(ctx, "the photo booth!", innerX, border + padIn + 118, {
    font: `italic 58px ${F.serif}`,
    color: frame.accent,
    align: "left",
  });
  drawText(ctx, "POST CARD · AIR MAIL", innerX, border + padIn + 160, {
    font: `18px ${F.mono}`,
    color: frame.ink,
    align: "left",
    alpha: 0.7,
    spacing: 5,
  });

  // stamp
  ctx.save();
  ctx.translate(W - innerX - 59, border + padIn + 70);
  ctx.rotate((4 * Math.PI) / 180);
  ctx.fillStyle = "rgba(179,52,42,0.12)";
  ctx.fillRect(-59, -70, 118, 140);
  ctx.strokeStyle = frame.ink;
  ctx.lineWidth = 8;
  ctx.setLineDash([2, 10]);
  ctx.lineCap = "round";
  ctx.strokeRect(-59, -70, 118, 140);
  ctx.restore();
  drawText(ctx, "SHUTTER", W - innerX - 59, border + padIn + 64, {
    font: `bold 19px ${F.mono}`,
    color: frame.ink,
  });
  drawText(ctx, "¢ 1", W - innerX - 59, border + padIn + 94, {
    font: `bold 22px ${F.mono}`,
    color: frame.ink,
  });

  // photos
  images.forEach((image, i) => {
    const x = innerX + (i % 2) * (cellW + gap);
    const y = gridTop + Math.floor(i / 2) * (cellH + gap);

    ctx.fillStyle = frame.ink;
    ctx.fillRect(x, y, cellW, cellH);
    drawCover(ctx, image, x + 8, y + 8, cellW - 16, cellH - 16);
  });

  // dotted rule + note
  ctx.save();
  ctx.strokeStyle = frame.ink;
  ctx.lineWidth = 3;
  ctx.setLineDash([2, 9]);
  ctx.lineCap = "round";
  ctx.beginPath();
  ctx.moveTo(innerX, ruleY);
  ctx.lineTo(innerX + innerW, ruleY);
  ctx.stroke();
  ctx.restore();

  lines.forEach((line, i) => {
    drawText(ctx, line, innerX, firstBase + i * 66, {
      font: noteFont,
      color: frame.ink,
      align: "left",
    });
  });
}

