// 1×4 vertical booth strip (classic / dark / red / pink)
function renderStrip({ canvas, images, frame, note, filmLabel }: RenderArgs) {
  const F = fontFamilies();
  const m = measureCtx();

  const W = 720;
  const pw = 620;
  const ph = 517;
  const b = 12;
  const gap = 24;
  const x = 50;
  const top = 170;
  const step = ph + b * 2 + gap;

  const noteFont = `700 58px ${F.hand}`;
  const lines = wrapText(m, note.trim() || "little memories", noteFont, 600).slice(0, 3);

  const blocksEnd = top + 3 * step + ph + b * 2;
  const lastBase = blocksEnd + 78 + (lines.length - 1) * 58;
  const H = lastBase + 110;

  const ctx = prepareCanvas(canvas, W, H);

  ctx.fillStyle = frame.paper;
  ctx.fillRect(0, 0, W, H);
  paperTexture(ctx, 0, 0, W, H);

  drawText(ctx, "SHUTTER", W / 2, 90, {
    font: `700 56px ${F.serif}`,
    color: frame.textColor,
    spacing: 12,
  });
  drawText(ctx, `PHOTO LAB · ${filmLabel.toUpperCase()}`, W / 2, 130, {
    font: `16px ${F.mono}`,
    color: frame.textColor,
    alpha: 0.7,
    spacing: 4,
  });

  images.forEach((image, i) => {
    const y = top + i * step + b;

    ctx.fillStyle = frame.ink;
    ctx.fillRect(x - b, y - b, pw + b * 2, ph + b * 2);
    drawCover(ctx, image, x, y, pw, ph);
  });

  lines.forEach((line, i) => {
    drawText(ctx, line, W / 2, blocksEnd + 78 + i * 58, {
      font: noteFont,
      color: frame.accent,
    });
  });

  drawText(ctx, "NO. 001 · 2026", W / 2, lastBase + 56, {
    font: `15px ${F.mono}`,
    color: frame.textColor,
    alpha: 0.6,
    spacing: 4,
  });
}

