const loadImage = (src: string, index: number) =>
  new Promise<HTMLImageElement>((resolve, reject) => {
    const image = new Image();
    image.onload = () => resolve(image);
    image.onerror = () => reject(new Error(`Gagal memuat foto ${index + 1}.`));
    image.src = src;
  });

const sleep = (ms: number) =>
  new Promise<void>((resolve) => window.setTimeout(resolve, ms));

const measureCtx = () => {
  const ctx = document.createElement("canvas").getContext("2d");
  if (!ctx) throw new Error("Canvas tidak didukung browser ini.");
  return ctx;
};

const prepareCanvas = (canvas: HTMLCanvasElement, w: number, h: number) => {
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("Gagal memproses photostrip.");
  return ctx;
};

const setSpacing = (ctx: Ctx, px: number) => {
  if ("letterSpacing" in ctx) {
    (ctx as unknown as { letterSpacing: string }).letterSpacing = `${px}px`;
  }
};

function drawText(
  ctx: Ctx,
  str: string,
  x: number,
  y: number,
  opts: {
    font: string;
    color: string;
    align?: CanvasTextAlign;
    alpha?: number;
    spacing?: number;
  }
) {
  ctx.save();
  ctx.font = opts.font;
  ctx.fillStyle = opts.color;
  ctx.textAlign = opts.align ?? "center";
  ctx.textBaseline = "alphabetic";
  ctx.globalAlpha = opts.alpha ?? 1;
  setSpacing(ctx, opts.spacing ?? 0);
  ctx.fillText(str, x, y);
  ctx.restore();
}

function wrapText(ctx: Ctx, text: string, font: string, maxWidth: number) {
  ctx.font = font;
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = "";

  words.forEach((word) => {
    const test = current ? `${current} ${word}` : word;

    if (ctx.measureText(test).width > maxWidth && current) {
      lines.push(current);
      current = word;
    } else {
      current = test;
    }
  });

  if (current) lines.push(current);
  return lines;
}

// Draws an image "object-fit: cover" into the box
function drawCover(
  ctx: Ctx,
  image: HTMLImageElement,
  x: number,
  y: number,
  w: number,
  h: number
) {
  const scale = Math.max(w / image.width, h / image.height);
  const cropW = w / scale;
  const cropH = h / scale;

  ctx.drawImage(
    image,
    (image.width - cropW) / 2,
    (image.height - cropH) / 2,
    cropW,
    cropH,
    x,
    y,
    w,
    h
  );
}

function roundRect(ctx: Ctx, x: number, y: number, w: number, h: number, r: number) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}

// Warm stains + dust speckles for paper
function paperTexture(ctx: Ctx, x: number, y: number, w: number, h: number) {
  ctx.save();
  ctx.beginPath();
  ctx.rect(x, y, w, h);
  ctx.clip();

  const a = ctx.createRadialGradient(x + w * 0.2, y + h * 0.08, 0, x + w * 0.2, y + h * 0.08, w * 0.8);
  a.addColorStop(0, "rgba(170,120,60,0.14)");
  a.addColorStop(1, "rgba(170,120,60,0)");
  ctx.fillStyle = a;
  ctx.fillRect(x, y, w, h);

  const b = ctx.createRadialGradient(x + w * 0.85, y + h * 0.92, 0, x + w * 0.85, y + h * 0.92, w * 0.9);
  b.addColorStop(0, "rgba(120,70,40,0.16)");
  b.addColorStop(1, "rgba(120,70,40,0)");
  ctx.fillStyle = b;
  ctx.fillRect(x, y, w, h);

  const count = Math.floor((w * h) / 450);
  for (let i = 0; i < count; i++) {
    ctx.fillStyle = `rgba(90,65,40,${Math.random() * 0.04})`;
    ctx.fillRect(x + Math.random() * w, y + Math.random() * h, 2, 2);
  }

  ctx.restore();
}

